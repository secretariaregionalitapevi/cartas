const test=require('node:test'),assert=require('node:assert/strict'),http=require('node:http');
test('músico inativo emite PDF e registra pendência interna para três responsáveis',async(t)=>{
 const {Store}=require('../src/store'),agenda=require('../src/agenda'),pdf=require('../src/pdf'),domain=require('../src/domain');
 const methods=['commons','people','ministry','rows','reserve','upload','update'];
 const original=Object.fromEntries(methods.map(k=>[k,Store.prototype[k]]));
 const originalAgenda=agenda.getAgenda,originalPdf=pdf.makePdf;
 let reserved,ready;
 const common='BR-22-2294 - JARDIM SANTA CECÍLIA';
 const person={id:'00000000-0000-4000-8000-000000000001',nome:'MUSICO INATIVO TESTE',instrumento:'SAXOFONE ALTO',nivel:'CANDIDATO(A)',status:'Alerta',tonalidade:'Mib'};
 const event={data:'2099-11-28',hora:'14:00',evento:'Avaliação de Músicos (Itapevi)'};
 Store.prototype.commons=async()=>[{comum:common,municipio:'Itapevi'}];
 Store.prototype.people=async()=>[person];
 Store.prototype.ministry=async()=>[['anciao','ANCIÃO'],['cooperador','COOPERADOR DO OFÍCIO'],['regional','ENCARREGADO REGIONAL'],['encarregado','ENCARREGADO LOCAL']].map(([id,ministerio])=>({id,nome:id.toUpperCase(),ministerio}));
 Store.prototype.rows=async table=>table==='sam_mirror_student_status'?[{operational_status:'INATIVO',inactive_days:250,last_activity_at:'2026-03-01',requires_review:false}]:[];
 Store.prototype.reserve=async record=>{reserved=record;return {...record,id:'00000000-0000-4000-8000-000000000002'};};
 Store.prototype.upload=async()=>{};
 Store.prototype.update=async(id,body)=>{ready=body;};
 agenda.getAgenda=async()=>({events:[event]});
 pdf.makePdf=async()=>Buffer.from('%PDF-mock');
 const handler=require('../src/server');
 const server=http.createServer(handler);await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));for(const name of methods)Store.prototype[name]=original[name];agenda.getAgenda=originalAgenda;pdf.makePdf=originalPdf;});
 const response=await fetch('http://127.0.0.1:'+server.address().port+'/api/letters',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({tipo:'musico',modalidade:'culto',municipio:'Itapevi',comum:common,nome:person.nome,instrumento:person.instrumento,tonalidade:'Mib',whatsapp:'11999999999',pessoa_id:person.id,evento_id:domain.eventId(event),anciao:'anciao',cooperador:'cooperador',regional:'regional',encarregado:'encarregado',consentimento:true})});
 assert.equal(response.status,201,JSON.stringify(await response.clone().json()));
 assert.equal((await response.json()).activity_pending,true);
 assert.equal(ready.status,'ready');
 assert.equal(reserved.payload.student_activity.status,'INATIVO');
 assert.equal(reserved.payload.activity_review.status,'pending');
 assert.equal(reserved.payload.activity_review.channel,'internal');
 assert.deepEqual(reserved.payload.activity_review.recipients.map(r=>r.role),['anciao_musica','encarregado_regional','secretario_regional']);
});
